async def get_available_profiles() -> list[tuple[str, str]]:
    try:
        async with get_pool().acquire() as conn:
            rows = await conn.fetch(
                "SELECT username, display_name FROM users ORDER BY LOWER(username) ASC LIMIT 12"
            )
        profiles: list[tuple[str, str]] = []
        for row in rows:
            uname = str(row["username"] or "").strip().lower()
            if is_valid_user_id(uname):
                label = str(row["display_name"] or uname).strip() or uname
                profiles.append((label, uname))
        if profiles:
            return profiles
    except asyncpg.UndefinedTableError:
        pass
    except Exception as e:
        logger.debug("Could not load users from PostgreSQL: %s", redact_secrets(e))
    return list(DEFAULT_PROFILES)


