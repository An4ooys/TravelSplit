def esc(value: Optional[str]) -> str:
    return html.escape(str(value or ""), quote=False)


def strip_command(text: str) -> str:
    return re.sub(r"^/[a-zA-Z0-9_]+(?:@[a-zA-Z0-9_]+)?\s*", "", (text or "").strip()).strip()


def is_valid_user_id(user_id: str) -> bool:
    return bool(VALID_USER_RE.match(user_id))


def verify_secret(provided: str) -> bool:
    if not WEBHOOK_SECRET:
        return True
    return hmac.compare_digest(provided or "", WEBHOOK_SECRET)


def ensure_utc_dt(value: Any) -> datetime:
    if isinstance(value, datetime):
        if value.tzinfo is None:
            return value.replace(tzinfo=timezone.utc)
        return value.astimezone(timezone.utc)
    if isinstance(value, str):
        return datetime.fromisoformat(value.replace("Z", "+00:00"))
    return datetime.now(timezone.utc)


def extract_retry_after(err: Exception) -> int:
    if hasattr(err, "result_json") and isinstance(err.result_json, dict):
        ra = err.result_json.get("parameters", {}).get("retry_after")
        if ra is not None:
            return int(ra) + 2
    match = re.search(r"retry after (\d+)", str(err), re.IGNORECASE)
    if match:
        return int(match.group(1)) + 2
    return 30


def is_permanent_telegram_error(err: Exception) -> bool:
    msg = str(err).lower()
    if "message is too long" in msg:
        return False
    code = getattr(err, "error_code", None)
    if code in (400, 403):
        return True
    return any(tok in msg for tok in ("blocked", "chat not found", "deactivated", "forbidden"))


def format_notification_message(icon: str, title: str, message: str) -> str:
    safe_title = esc(title[:200])
    header = f"{icon} <b>Уведомление TravelSplit:</b>\n\n<b>{safe_title}</b>"
    footer = "\n\nВы можете отложить напоминание или отметить как прочитанное:"
    if not message:
        return header + footer
    max_body = max(0, 3900 - len(header) - len(footer))
    safe_body = esc(message)
    if len(safe_body) > max_body:
        safe_body = safe_body[: max(0, max_body - 1)] + "…"
    return f"{header}\n{safe_body}{footer}"


async def send_telegram_with_retry(
    chat_id: int,
    text: str,
    reply_markup: types.InlineKeyboardMarkup,
) -> tuple[bool, bool]:
    for attempt in range(2):
        try:
            await bot.send_message(chat_id, text, reply_markup=reply_markup)
            return True, False
        except Exception as e:
            if attempt == 0 and ("429" in str(e) or getattr(e, "error_code", None) == 429):
                await asyncio.sleep(extract_retry_after(e))
                continue
            logger.warning("Failed sending Telegram message to chat %s: %s", chat_id, redact_secrets(e))
            return False, is_permanent_telegram_error(e)
    return False, False


