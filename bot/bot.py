http_session: Optional[aiohttp.ClientSession] = None


def get_pool() -> asyncpg.Pool:
    if db_pool is None:
        raise RuntimeError("PostgreSQL pool is not initialized")
    return db_pool


async def get_http() -> aiohttp.ClientSession:
    global http_session
    if http_session is None or http_session.closed:
        http_session = aiohttp.ClientSession(connector=aiohttp.TCPConnector(limit=20))
    return http_session


SCHEMA_SQL = """
CREATE TABLE IF NOT EXISTS telegram_chat_bindings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_id BIGINT NOT NULL,
    user_id VARCHAR(255) NOT NULL,
    telegram_username VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_tg_user_id ON telegram_chat_bindings (user_id);
CREATE UNIQUE INDEX IF NOT EXISTS idx_tg_chat_id ON telegram_chat_bindings (chat_id);

CREATE TABLE IF NOT EXISTS telegram_reminders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_id BIGINT NOT NULL,
    user_id VARCHAR(255) NOT NULL,
    title VARCHAR(255) NOT NULL,
    description VARCHAR(1000),
    remind_at TIMESTAMPTZ NOT NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'PENDING',
    notification_id BIGINT,
    snooze_count INT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_remind_status_time ON telegram_reminders (status, remind_at);
"""


async def init_db() -> None:
    global db_pool
    delay = 1
    while True:
        try:
            db_pool = await asyncpg.create_pool(dsn=DATABASE_URL, min_size=1, max_size=10)
            async with db_pool.acquire() as conn:
                await conn.execute(SCHEMA_SQL)
            logger.info("Connected to PostgreSQL")
            return
        except asyncio.CancelledError:
            raise
        except Exception as e:
            if db_pool is not None:
                await db_pool.close()
                db_pool = None
            logger.warning("Waiting for PostgreSQL (%s). Retrying in %ss...", e, delay)
            await asyncio.sleep(delay)
            delay = min(15, delay * 2)


async def get_binding(chat_id: int) -> Optional[dict[str, Any]]:
    async with get_pool().acquire() as conn:
        row = await conn.fetchrow(
            "SELECT user_id, telegram_username FROM telegram_chat_bindings WHERE chat_id = $1",
            chat_id,
        )
        return dict(row) if row else None


async def save_binding(chat_id: int, user_id: str, username: Optional[str]) -> None:
    now_dt = datetime.now(timezone.utc)
    normalized_user = user_id.strip().lower()
    async with get_pool().acquire() as conn:
        await conn.execute(
            """
            INSERT INTO telegram_chat_bindings (chat_id, user_id, telegram_username, created_at)
            VALUES ($1, $2, $3, $4)
            ON CONFLICT (chat_id) DO UPDATE SET
                user_id = EXCLUDED.user_id,
                telegram_username = EXCLUDED.telegram_username,
                created_at = EXCLUDED.created_at
            """,
            chat_id,
            normalized_user,
            username,
            now_dt,
        )


async def insert_reminder(
    chat_id: int,
    user_id: str,
    title: str,
    remind_at: datetime,
    status: str = "PENDING",
    notification_id: Optional[int] = None,
) -> int:
    now_dt = datetime.now(timezone.utc)
    async with get_pool().acquire() as conn:
        rem_id = await conn.fetchval(
            """
            INSERT INTO telegram_reminders
                (chat_id, user_id, title, remind_at, status, snooze_count, notification_id, created_at, updated_at)
            VALUES ($1, $2, $3, $4, $5, 0, $6, $7, $7)
            RETURNING id
            """,
            chat_id,
            user_id.strip().lower(),
            title[:255],
            remind_at,
            status,
            notification_id,
            now_dt,
        )
        return int(rem_id)


async def get_active_reminders(chat_id: int) -> list[dict[str, Any]]:
    async with get_pool().acquire() as conn:
        rows = await conn.fetch(
            """
            SELECT id, chat_id, user_id, title, remind_at, status, notification_id, snooze_count
            FROM telegram_reminders
            WHERE chat_id = $1 AND status IN ('PENDING', 'SNOOZED', 'DELIVERED')
            ORDER BY remind_at ASC
            """,
            chat_id,
        )
        return [dict(r) for r in rows]


async def get_reminder_by_id(reminder_id: int) -> Optional[dict[str, Any]]:
    async with get_pool().acquire() as conn:
        row = await conn.fetchrow("SELECT * FROM telegram_reminders WHERE id = $1", reminder_id)
        return dict(row) if row else None


async def update_reminder_snooze(reminder_id: int, new_remind_at: datetime) -> None:
    now_dt = datetime.now(timezone.utc)
    async with get_pool().acquire() as conn:
        await conn.execute(
            """
            UPDATE telegram_reminders
            SET remind_at = $1, status = 'SNOOZED', snooze_count = snooze_count + 1, updated_at = $2
            WHERE id = $3
            """,
            new_remind_at,
            now_dt,
            reminder_id,
        )


async def mark_reminder_status(reminder_id: int, status: str) -> None:
    now_dt = datetime.now(timezone.utc)
    async with get_pool().acquire() as conn:
        await conn.execute(
            "UPDATE telegram_reminders SET status = $1, updated_at = $2 WHERE id = $3",
            status,
            now_dt,
            reminder_id,
        )


