def esc(value: Optional[str]) -> str:
    return html.escape(str(value or ""), quote=False)


def strip_command(text: str) -> str:
    return re.sub(r"^/[a-zA-Z0-9_]+(?:@[a-zA-Z0-9_]+)?\s*", "", (text or "").strip()).strip()


def is_valid_user_id(user_id: str) -> bool:
    return bool(VALID_USER_RE.match(user_id))


def parse_reminder_text(payload: str) -> tuple[str, int]:
    parts = payload.strip().split()
    if not parts:
        return "Напоминание", 15
    if len(parts) == 1:
        return parts[0][:255], 15

    last = parts[-1].lower()
    minutes: Optional[int] = None

    m_min = re.match(r"^(\d+)(?:m|м|мин|min)$", last)
    m_hr = re.match(r"^(\d+)(?:h|ч|час|часа|часов)$", last)
    m_day = re.match(r"^(\d+)(?:d|д|дн|дня|дней|день)$", last)

    if m_min:
        minutes = min(MAX_REMINDER_MINUTES, max(1, int(m_min.group(1))))
    elif m_hr:
        minutes = min(MAX_REMINDER_MINUTES, max(1, int(m_hr.group(1))) * 60)
    elif m_day:
        minutes = min(MAX_REMINDER_MINUTES, max(1, int(m_day.group(1))) * 1440)
    elif re.match(r"^\d{1,2}:\d{2}$", last):
        hh, mm = map(int, last.split(":"))
        if 0 <= hh <= 23 and 0 <= mm <= 59:
            now = datetime.now(MSK_TZ)
            target = now.replace(hour=hh, minute=mm, second=0, microsecond=0)
            if target <= now:
                target += timedelta(days=1)
            minutes = max(1, int((target - now).total_seconds() // 60))

    if minutes is not None:
        title = " ".join(parts[:-1]).strip()[:255]
        return (title or "Напоминание"), minutes

    return payload.strip()[:255], 15


def format_dt(dt: datetime) -> str:
    return dt.strftime("%d.%m %H:%M")


@bot.message_handler(commands=["start"])
async def cmd_start(message: types.Message) -> None:
    chat_id = message.chat.id
    username = message.from_user.username if message.from_user else None

    user_to_link = strip_command(message.text or "").lower()
    if user_to_link:
        if not is_valid_user_id(user_to_link):
            await bot.send_message(chat_id, "❌ Некорректное имя профиля.", reply_markup=quick_link_keyboard())
            return
        await save_binding(chat_id, user_to_link, username)
        await bot.send_message(
            chat_id,
            f"✅ Профиль <b>{esc(user_to_link)}</b> привязан!",
            reply_markup=main_menu_keyboard(),
        )
        return

    binding = await get_binding(chat_id)
    if binding:
        await bot.send_message(
            chat_id,
            f"👋 Вы авторизованы как <b>{esc(binding['user_id'])}</b>.",
            reply_markup=main_menu_keyboard(),
        )
    else:
        await bot.send_message(
            chat_id,
            "👋 <b>Добро пожаловать в TravelSplit Бот!</b>\nВыберите профиль:",
            reply_markup=quick_link_keyboard(),
        )


