_TIME_MIN_RE = re.compile(r"^(\d+)(?:m|м|мин|min)$")
_TIME_HR_RE = re.compile(r"^(\d+)(?:h|ч|час|часа|часов)$")
_TIME_DAY_RE = re.compile(r"^(\d+)(?:d|д|дн|дня|дней|день)$")


def parse_reminder_text(payload: str) -> tuple[str, int]:
    parts = payload.strip().split()
    if not parts:
        return "Напоминание", 15
    if len(parts) == 1:
        return parts[0][:255], 15

    last = parts[-1].lower()
    minutes: Optional[int] = None
    consumed = 1

    m_min = _TIME_MIN_RE.match(last)
    m_hr = _TIME_HR_RE.match(last)
    m_day = _TIME_DAY_RE.match(last)

    if m_min:
        minutes = min(MAX_REMINDER_MINUTES, max(1, int(m_min.group(1))))
    elif m_hr:
        minutes = min(MAX_REMINDER_MINUTES, max(1, int(m_hr.group(1))) * 60)
    elif m_day:
        minutes = min(MAX_REMINDER_MINUTES, max(1, int(m_day.group(1))) * 1440)
    elif re.match(r"^\d{1,2}:\d{2}$", last):
        hh, mm = map(int, last.split(":"))
        if 0 <= hh <= 23 and 0 <= mm <= 59:
            now = datetime.now(MSK_TZ)
            target = now.replace(hour=hh, minute=mm, second=0, microsecond=0)
            if target <= now:
                target += timedelta(days=1)
            minutes = max(1, int((target - now).total_seconds() // 60))
    elif len(parts) >= 3 and parts[-2].isdigit():
        qty = int(parts[-2])
        if last in ("m", "м", "мин", "мин.", "минут", "минуту", "минуты", "min"):
            minutes = min(MAX_REMINDER_MINUTES, max(1, qty))
            consumed = 2
        elif last in ("h", "ч", "ч.", "час", "часа", "часов"):
            minutes = min(MAX_REMINDER_MINUTES, max(1, qty) * 60)
            consumed = 2
        elif last in ("d", "д", "дн", "дней", "дня", "день"):
            minutes = min(MAX_REMINDER_MINUTES, max(1, qty) * 1440)
            consumed = 2

    if minutes is not None:
        if len(parts) > consumed + 1 and parts[-consumed - 1].lower() in ("через", "в", "на"):
            consumed += 1
        title = " ".join(parts[:-consumed]).strip()[:255]
        return (title or "Напоминание"), minutes

    return payload.strip()[:255], 15


def format_dt(dt: datetime) -> str:
    return dt.strftime("%d.%m %H:%M")


async def deliver_notification_to_chats(
    notif_id: Optional[int],
    user_id: str,
    notif_type: str,
    title: str,
    message: str,
    target_chat_ids: Optional[list[int]] = None,
) -> int:
    chat_ids = target_chat_ids if target_chat_ids is not None else await get_chats_by_user(user_id)
    if not chat_ids:
        return 0

    icon = NOTIFICATION_ICONS.get(notif_type, "🔔")
    now_dt = datetime.now(timezone.utc)
    delivered_count = 0

    async def deliver_one(chat_id: int) -> None:
        nonlocal delivered_count
        try:
            rem_id = await try_claim_notification_delivery(
                chat_id, user_id, title, message, now_dt, notif_id
            )
            if rem_id is None:
                return

            msg_text = format_notification_message(icon, title, message)
            ok, permanent = await send_telegram_with_retry(
                chat_id, msg_text, notification_action_keyboard(notif_id or 0, rem_id)
            )
            if ok:
                delivered_count += 1
            elif not permanent:
                # При временном сбое сети снимаем бронь, чтобы догон повторил доставку
                await unclaim_notification_delivery(chat_id, notif_id, rem_id)
        except Exception as e:
            logger.error("Unexpected error delivering notification %s to chat %s: %s", notif_id, chat_id, redact_secrets(e))

    await asyncio.gather(*(deliver_one(cid) for cid in chat_ids))
    return delivered_count


async def fetch_and_deliver_notification(notif_id: int) -> None:
    async with get_pool().acquire() as conn:
        row = await conn.fetchrow(
            """
            SELECT id, user_id, notification_type, title, message, is_read
            FROM notifications
            WHERE id = $1
            """,
            notif_id,
        )
    if not row or row["is_read"]:
        return

    user_id = str(row["user_id"] or "").strip().lower()
    if not is_valid_user_id(user_id):
        return

    await deliver_notification_to_chats(
        notif_id=int(row["id"]),
        user_id=user_id,
        notif_type=str(row["notification_type"] or ""),
        title=str(row["title"] or "Уведомление TravelSplit")[:255],
        message=str(row["message"] or "")[:1000],
    )


async def sync_undelivered_notifications(lookback_hours: int = 24) -> None:
    cutoff = datetime.now(timezone.utc) - timedelta(hours=lookback_hours)
    async with get_pool().acquire() as conn:
        rows = await conn.fetch(
            """
            SELECT n.id, n.user_id, n.notification_type, n.title, n.message, b.chat_id
            FROM notifications n
            JOIN telegram_chat_bindings b ON LOWER(b.user_id) = LOWER(n.user_id)
            LEFT JOIN telegram_delivered_notifications d
                   ON d.notification_id = n.id AND d.chat_id = b.chat_id
            WHERE n.is_read = FALSE
              AND n.delivered_at >= $1
              AND d.notification_id IS NULL
            ORDER BY n.id ASC
            LIMIT 100
            """,
            cutoff,
        )
    tasks = []
    for r in rows:
        user_id = str(r["user_id"] or "").strip().lower()
        if not is_valid_user_id(user_id):
            continue
        tasks.append(
            deliver_notification_to_chats(
                notif_id=int(r["id"]),
                user_id=user_id,
                notif_type=str(r["notification_type"] or ""),
                title=str(r["title"] or "Уведомление TravelSplit")[:255],
                message=str(r["message"] or "")[:1000],
                target_chat_ids=[int(r["chat_id"])],
            )
        )
    if tasks:
        await asyncio.gather(*tasks, return_exceptions=True)


def schedule_catchup_sync() -> None:
    async def _runner() -> None:
        try:
            await sync_undelivered_notifications()
        except Exception as e:
            logger.debug("Catchup sync skipped: %s", redact_secrets(e))

    asyncio.create_task(_runner())


