def redact_dsn(dsn: str) -> str:
    return re.sub(r"://([^:/@]+):[^@]+@", r"://\1:***@", dsn)


def redact_secrets(value: Any) -> str:
    text = redact_dsn(str(value or ""))
    if BOT_TOKEN:
        text = text.replace(BOT_TOKEN, "***")
    if WEBHOOK_SECRET:
        text = text.replace(WEBHOOK_SECRET, "***")
    return text


async def init_db() -> None:
    global db_pool
    delay = 1
    while True:
        try:
            db_pool = await asyncpg.create_pool(
                dsn=DATABASE_URL,
                min_size=1,
                max_size=10,
                command_timeout=15,
            )
            async with db_pool.acquire() as conn:
                await conn.execute(SCHEMA_SQL)
            logger.info("Connected to PostgreSQL: %s", redact_dsn(DATABASE_URL))
            return
        except asyncio.CancelledError:
            raise
        except Exception as e:
            if db_pool is not None:
                await db_pool.close()
                db_pool = None
            logger.warning(
                "PostgreSQL unavailable (%s): %s. Retrying in %ss...",
                redact_dsn(DATABASE_URL),
                redact_secrets(e),
                delay,
            )
            await asyncio.sleep(delay)
            delay = min(15, delay * 2)


