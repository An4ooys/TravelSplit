async def handle_backend_notification_webhook(request: web.Request) -> web.Response:
    if not verify_secret(request.headers.get("X-Webhook-Secret", "")):
        return web.json_response({"error": "unauthorized"}, status=401)

    try:
        payload = await request.json()
    except Exception:
        return web.json_response({"error": "invalid_json"}, status=400)

    if not isinstance(payload, dict):
        return web.json_response({"error": "invalid_payload"}, status=400)

    n_id = payload.get("id")
    notif_int: Optional[int] = None
    if n_id is not None:
        try:
            notif_int = int(n_id)
        except (TypeError, ValueError):
            return web.json_response({"error": "invalid_notification_id"}, status=400)
        if notif_int <= 0:
            return web.json_response({"error": "invalid_notification_id"}, status=400)

    user_id = str(payload.get("userId") or "").strip().lower()
    if not is_valid_user_id(user_id):
        return web.json_response({"error": "invalid_userId"}, status=400)

    delivered_count = await deliver_notification_to_chats(
        notif_id=notif_int,
        user_id=user_id,
        notif_type=str(payload.get("type") or ""),
        title=str(payload.get("title") or "Уведомление TravelSplit")[:255],
        message=str(payload.get("description") or payload.get("message") or "")[:1000],
    )
    if delivered_count == 0 and not await get_chats_by_user(user_id):
        return web.json_response({"status": "no_bound_chats", "delivered": 0})
    return web.json_response({"status": "ok", "delivered": delivered_count})


async def handle_telegram_webhook(request: web.Request) -> web.Response:
    if not TELEGRAM_WEBHOOK_URL or not WEBHOOK_SECRET:
        return web.Response(status=403, text="Forbidden")
    if not verify_secret(request.headers.get("X-Telegram-Bot-Api-Secret-Token", "")):
        return web.Response(status=401, text="Unauthorized")

    try:
        data = await request.json()
        update = types.Update.de_json(data)
        if update:
            await bot.process_new_updates([update])
        return web.Response(status=200, text="OK")
    except Exception as e:
        logger.error("Error processing Telegram webhook update: %s", redact_secrets(e))
        return web.Response(status=500, text="Error")


def on_pg_notification(
    _conn: asyncpg.Connection, _pid: int, _channel: str, payload: str
) -> None:
    if notify_queue is None:
        return
    try:
        data = json.loads(payload)
        notif_id = int(data["id"])
        notify_queue.put_nowait(notif_id)
    except Exception as e:
        logger.debug("Ignored malformed pg_notify payload %r: %s", payload, redact_secrets(e))


async def pg_notifications_worker() -> None:
    global notify_queue
    notify_queue = asyncio.Queue()

    while True:
        listener_conn: Optional[asyncpg.Connection] = None
        try:
            listener_conn = await asyncpg.connect(dsn=DATABASE_URL)
            await listener_conn.add_listener("new_notification", on_pg_notification)
            logger.info("Listening on PostgreSQL channel 'new_notification'")

            await sync_undelivered_notifications()

            while True:
                try:
                    notif_id = await asyncio.wait_for(notify_queue.get(), timeout=30.0)
                    await fetch_and_deliver_notification(notif_id)
                except asyncio.TimeoutError:
                    await listener_conn.execute("SELECT 1")
                    await sync_undelivered_notifications()
        except asyncio.CancelledError:
            break
        except Exception as e:
            logger.warning("PostgreSQL listener error: %s. Reconnecting in 5s...", redact_secrets(e))
            await asyncio.sleep(5)
        finally:
            if listener_conn is not None:
                try:
                    await listener_conn.remove_listener("new_notification", on_pg_notification)
                except Exception:
                    pass
                try:
                    await listener_conn.close()
                except Exception:
                    pass


async def deliver_due_reminder(r: dict[str, Any]) -> None:
    chat_id = int(r["chat_id"])
    rem_id = int(r["id"])
    snooze_text = f" (перенесено: {r['snooze_count']} раз)" if r["snooze_count"] > 0 else ""
    msg_text = (
        f"⏰ <b>Напоминание!</b>\n\n"
        f"📌 <b>{esc(r['title'])}</b>{snooze_text}\n\n"
        f"Вы можете отложить задачу кнопками ниже:"
    )
    ok, permanent = await send_telegram_with_retry(
        chat_id, msg_text, reminder_action_keyboard(rem_id)
    )
    if not ok and not permanent:
        fallback_status = "SNOOZED" if r["snooze_count"] > 0 else "PENDING"
        try:
            await mark_reminder_status(rem_id, fallback_status)
        except Exception as e:
            logger.warning("Failed restoring reminder %s after transient error: %s", rem_id, redact_secrets(e))


async def due_reminders_worker() -> None:
    logger.info("Started due_reminders_worker async task")
    while True:
        try:
            due = await claim_due_reminders(datetime.now(timezone.utc))
            if due:
                await asyncio.gather(
                    *(deliver_due_reminder(r) for r in due),
                    return_exceptions=True,
                )
        except asyncio.CancelledError:
            break
        except Exception as e:
            logger.error("Error in due_reminders_worker: %s", redact_secrets(e))

        await asyncio.sleep(2)


async def telegram_polling_loop() -> None:
    logger.info("Checking bot authorization with Telegram...")
    while True:
        try:
            me = await bot.get_me()
            logger.info("Bot connected as @%s (%s)", me.username, me.first_name)
            break
        except asyncio.CancelledError:
            return
        except Exception as e:
            if "429" in str(e) or getattr(e, "error_code", None) == 429:
                wait_sec = extract_retry_after(e)
                logger.warning("Telegram 429 rate limit. Waiting %ss before resuming...", wait_sec)
                await asyncio.sleep(wait_sec)
            else:
                logger.error("Error checking bot auth: %s. Retrying in 5s...", redact_secrets(e))
                await asyncio.sleep(5)

    offset = 0
    logger.info("Starting Telegram long polling (set TELEGRAM_WEBHOOK_URL for Telegram push mode)...")
    while True:
        try:
            updates = await bot.get_updates(offset=offset, timeout=20, request_timeout=25)
            if updates:
                offset = updates[-1].update_id + 1
                await bot.process_new_updates(updates)
        except asyncio.CancelledError:
            break
        except Exception as e:
            if "429" in str(e) or getattr(e, "error_code", None) == 429:
                wait_sec = extract_retry_after(e)
                logger.warning("Telegram 429 rate limit during polling. Sleeping %ss...", wait_sec)
                await asyncio.sleep(wait_sec)
            else:
                logger.warning("Polling network error: %s. Reconnecting in 3s...", redact_secrets(e))
                await asyncio.sleep(3)


async def main() -> None:
    if not BOT_TOKEN:
        raise RuntimeError("BOT_TOKEN is not set. Configure BOT_TOKEN in bot/.env before starting the bot.")
    if TELEGRAM_WEBHOOK_URL and not WEBHOOK_SECRET:
        raise RuntimeError("WEBHOOK_SECRET must be set when TELEGRAM_WEBHOOK_URL is configured.")
    if not WEBHOOK_SECRET and BOT_WEBHOOK_HOST not in LOOPBACK_HOSTS:
        logger.warning(
            "BOT_WEBHOOK_HOST=%s without WEBHOOK_SECRET exposes webhook endpoints beyond localhost",
            BOT_WEBHOOK_HOST,
        )

    await init_db()
    await get_http()

    app = web.Application(client_max_size=256 * 1024)
    app.router.add_get("/health", handle_health)
    app.router.add_post("/webhook/notifications", handle_backend_notification_webhook)
    app.router.add_post("/webhook/telegram", handle_telegram_webhook)

    runner = web.AppRunner(app)
    await runner.setup()
    site = web.TCPSite(runner, BOT_WEBHOOK_HOST, BOT_WEBHOOK_PORT)
    await site.start()
    logger.info("Webhook server listening on http://%s:%s", BOT_WEBHOOK_HOST, BOT_WEBHOOK_PORT)

    pg_listener_task = asyncio.create_task(pg_notifications_worker())
    reminders_task = asyncio.create_task(due_reminders_worker())
    polling_task = None

    try:
        if TELEGRAM_WEBHOOK_URL:
            await bot.set_webhook(url=TELEGRAM_WEBHOOK_URL, secret_token=WEBHOOK_SECRET)
            logger.info("Telegram webhook registered at %s", TELEGRAM_WEBHOOK_URL)
            await asyncio.Event().wait()
        else:
            try:
                await bot.delete_webhook()
            except Exception:
                pass
            polling_task = asyncio.create_task(telegram_polling_loop())
            await polling_task
    finally:
        pg_listener_task.cancel()
        reminders_task.cancel()
        if polling_task:
            polling_task.cancel()
        await runner.cleanup()
        if http_session and not http_session.closed:
            await http_session.close()
        if db_pool is not None:
            await db_pool.close()
        try:
            await bot.close_session()
        except Exception:
            pass


if __name__ == "__main__":
    try:
        asyncio.run(main())
    except (KeyboardInterrupt, SystemExit):
        logger.info("Bot stopped by user.")
