def load_env(path: str) -> None:
    if not os.path.exists(path):
        return
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            k, v = line.split("=", 1)
            os.environ.setdefault(k.strip(), v.strip())


load_env(ENV_PATH)


def build_database_url() -> str:
    explicit = os.getenv("DATABASE_URL", "").strip()
    if explicit:
        return explicit
    host = os.getenv("POSTGRES_HOST", "127.0.0.1").strip()
    port = os.getenv("POSTGRES_PORT", "5432").strip()
    db_name = os.getenv("POSTGRES_DB", "travelsplit").strip()
    user = quote_plus(os.getenv("POSTGRES_USER", "travelsplit").strip())
    password = quote_plus(os.getenv("POSTGRES_PASSWORD", "travelsplit").strip())
    return f"postgresql://{user}:{password}@{host}:{port}/{db_name}"


