@bot.callback_query_handler(func=lambda call: True)
async def handle_callback(call: types.CallbackQuery) -> None:
    if not call.message:
        await bot.answer_callback_query(call.id)
        return
    data = call.data or ""
    chat_id = call.message.chat.id
    message_id = call.message.message_id

    if data.startswith("link:"):
        user_id = data.split(":", 1)[1].strip().lower()
        username = call.from_user.username if call.from_user else None
        await save_binding(chat_id, user_id, username)
        await bot.answer_callback_query(call.id, f"Профиль {user_id} привязан!")
        await bot.edit_message_text(
            f"✅ Профиль <b>{esc(user_id)}</b> привязан.",
            chat_id=chat_id,
            message_id=message_id,
            reply_markup=main_menu_keyboard(),
        )
        return

    if data == "nav_trips":
        await bot.answer_callback_query(call.id)
        await send_trips_info(chat_id)
    elif data == "nav_reminders":
        await bot.answer_callback_query(call.id)
        await send_reminders_list(chat_id)
    elif data == "nav_link":
        await bot.answer_callback_query(call.id)
        await bot.send_message(chat_id, "Выберите профиль:", reply_markup=quick_link_keyboard())
    elif data == "nav_help":
        await bot.answer_callback_query(call.id)
        await cmd_help(call.message)
    elif data.startswith("qrem:"):
        mins = max(1, int(data.split(":", 2)[1]))
        remind_at = datetime.now(timezone.utc) + timedelta(minutes=mins)
        binding = await get_binding(chat_id)
        rem_id = await insert_reminder(chat_id, binding["user_id"] if binding else "anna", "Собрать вещи", remind_at)
        await bot.answer_callback_query(call.id, f"Поставил на {mins}м")
        await bot.edit_message_text(
            f"✅ Напоминание создано на {mins} мин.",
            chat_id=chat_id,
            message_id=message_id,
            reply_markup=reminder_action_keyboard(rem_id),
        )
    elif data.startswith("snooze:"):
        _, mins_str, rem_id_str = data.split(":", 2)
        mins = max(1, int(mins_str))
        rem_id = int(rem_id_str)
        await update_reminder_snooze(rem_id, datetime.now(timezone.utc) + timedelta(minutes=mins))
        await bot.answer_callback_query(call.id, f"Отложено на {mins} мин")
    elif data.startswith("done:"):
        rem_id = int(data.split(":", 1)[1])
        await mark_reminder_status(rem_id, "COMPLETED")
        await bot.answer_callback_query(call.id, "Выполнено!")
    elif data.startswith("cancel:"):
        rem_id = int(data.split(":", 1)[1])
        await mark_reminder_status(rem_id, "CANCELLED")
        await bot.answer_callback_query(call.id, "Отменено")


async def due_reminders_worker() -> None:
    while True:
        try:
            async with get_pool().acquire() as conn:
                due = await conn.fetch(
                    """
                    UPDATE telegram_reminders
                    SET status = 'DELIVERED', updated_at = $1
                    WHERE id IN (
                        SELECT id FROM telegram_reminders
                        WHERE status IN ('PENDING', 'SNOOZED') AND remind_at <= $1
                        ORDER BY remind_at ASC
                        FOR UPDATE SKIP LOCKED
                        LIMIT 100
                    )
                    RETURNING id, chat_id, title, snooze_count
                    """,
                    datetime.now(timezone.utc),
                )
            for r in due:
                await bot.send_message(
                    int(r["chat_id"]),
                    f"⏰ <b>Напоминание:</b> {esc(r['title'])}",
                    reply_markup=reminder_action_keyboard(int(r["id"])),
                )
        except asyncio.CancelledError:
            break
        except Exception as e:
            logger.error("Error in due_reminders_worker: %s", e)
        await asyncio.sleep(2)


async def telegram_polling_loop() -> None:
    offset = 0
    while True:
        try:
            updates = await bot.get_updates(offset=offset, timeout=20, request_timeout=25)
            if updates:
                offset = updates[-1].update_id + 1
                await bot.process_new_updates(updates)
        except asyncio.CancelledError:
            break
        except Exception as e:
            logger.warning("Polling error: %s", e)
            await asyncio.sleep(3)


async def main() -> None:
    if not BOT_TOKEN:
        raise RuntimeError("BOT_TOKEN is not set.")
    await init_db()
    await get_http()
    reminders_task = asyncio.create_task(due_reminders_worker())
    try:
        await telegram_polling_loop()
    finally:
        reminders_task.cancel()
        if http_session and not http_session.closed:
            await http_session.close()
        if db_pool is not None:
            await db_pool.close()


if __name__ == "__main__":
    asyncio.run(main())
