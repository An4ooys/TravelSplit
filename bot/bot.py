async def try_claim_notification_delivery(
    chat_id: int,
    user_id: str,
    title: str,
    description: Optional[str],
    now_dt: datetime,
    notif_id: Optional[int],
) -> Optional[int]:
    async with get_pool().acquire() as conn:
        async with conn.transaction():
            if notif_id is not None:
                claimed = await conn.fetchval(
                    """
                    INSERT INTO telegram_delivered_notifications (notification_id, chat_id, delivered_at)
                    VALUES ($1, $2, $3)
                    ON CONFLICT (notification_id, chat_id) DO NOTHING
                    RETURNING notification_id
                    """,
                    notif_id,
                    chat_id,
                    now_dt,
                )
                if claimed is None:
                    return None

            rem_id = await conn.fetchval(
                """
                INSERT INTO telegram_reminders
                    (chat_id, user_id, title, description, remind_at, status, snooze_count, notification_id, created_at, updated_at)
                VALUES ($1, $2, $3, $4, $5, 'DELIVERED', 0, $6, $5, $5)
                RETURNING id
                """,
                chat_id,
                user_id.strip().lower(),
                title[:255],
                description[:1000] if description else None,
                now_dt,
                notif_id,
            )
            return int(rem_id)


async def unclaim_notification_delivery(chat_id: int, notif_id: Optional[int], rem_id: int) -> None:
    async with get_pool().acquire() as conn:
        async with conn.transaction():
            await conn.execute("DELETE FROM telegram_reminders WHERE id = $1", rem_id)
            if notif_id is not None:
                await conn.execute(
                    "DELETE FROM telegram_delivered_notifications WHERE notification_id = $1 AND chat_id = $2",
                    notif_id,
                    chat_id,
                )


async def claim_due_reminders(now_dt: datetime) -> list[dict[str, Any]]:
    async with get_pool().acquire() as conn:
        rows = await conn.fetch(
            """
            WITH due AS (
                SELECT id
                FROM telegram_reminders
                WHERE status IN ('PENDING', 'SNOOZED') AND remind_at <= $1
                ORDER BY remind_at ASC
                FOR UPDATE SKIP LOCKED
                LIMIT 100
            )
            UPDATE telegram_reminders r
            SET status = 'DELIVERED', updated_at = $1
            FROM due
            WHERE r.id = due.id
            RETURNING r.id, r.chat_id, r.user_id, r.title, r.description, r.remind_at, r.snooze_count, r.notification_id
            """,
            now_dt,
        )
        return [dict(r) for r in rows]


async def fetch_upcoming_events_from_db(user_id: str) -> list[dict[str, Any]]:
    cutoff = datetime.now(timezone.utc) - timedelta(hours=6)
    try:
        async with get_pool().acquire() as conn:
            rows = await conn.fetch(
                """
                WITH user_trips AS (
                    SELECT tr.id, tr.title, tr.destination, tr.starts_on, tr.ends_on, tr.description
                    FROM trips tr
                    JOIN teams tm_team ON tm_team.id = tr.team_id
                    JOIN users u ON LOWER(u.username) = LOWER($1)
                    WHERE tm_team.owner_user_id = u.id
                       OR EXISTS (
                           SELECT 1 FROM team_memberships tm
                           WHERE tm.team_id = tr.team_id AND tm.user_id = u.id
                       )
                )
                SELECT title, trip_title, event_time, description FROM (
                    SELECT
                        b.title,
                        ut.title AS trip_title,
                        COALESCE(b.starts_at, (ut.starts_on + TIME '09:00') AT TIME ZONE 'Europe/Moscow') AS event_time,
                        COALESCE(
                            NULLIF(b.notes, ''),
                            CASE WHEN b.reference_code IS NOT NULL AND b.reference_code <> ''
                                 THEN 'Бронь №' || b.reference_code
                                 ELSE ut.destination
                            END
                        ) AS description
                    FROM bookings b
                    JOIN user_trips ut ON ut.id = b.trip_id
                    WHERE COALESCE(b.starts_at, (ut.starts_on + TIME '09:00') AT TIME ZONE 'Europe/Moscow') >= $2::timestamptz

                    UNION ALL

                    SELECT
                        ii.title,
                        ut.title AS trip_title,
                        ((ii.item_date + COALESCE(ii.item_time, TIME '09:00')) AT TIME ZONE 'Europe/Moscow') AS event_time,
                        COALESCE(NULLIF(ii.location, ''), NULLIF(ii.notes, ''), ut.destination) AS description
                    FROM itinerary_items ii
                    JOIN user_trips ut ON ut.id = ii.trip_id
                    WHERE ((ii.item_date + COALESCE(ii.item_time, TIME '09:00')) AT TIME ZONE 'Europe/Moscow') >= $2::timestamptz
                ) combined
                ORDER BY event_time ASC
                LIMIT 20
                """,
                user_id,
                cutoff,
            )

            if not rows:
                rows = await conn.fetch(
                    """
                    SELECT
                        'Поездка: ' || tr.title AS title,
                        COALESCE(NULLIF(tr.destination, ''), tr.title) AS trip_title,
                        (tr.starts_on + TIME '09:00') AT TIME ZONE 'Europe/Moscow' AS event_time,
                        COALESCE(tr.description, '') AS description
                    FROM trips tr
                    JOIN teams tm_team ON tm_team.id = tr.team_id
                    JOIN users u ON LOWER(u.username) = LOWER($1)
                    WHERE (
                        tm_team.owner_user_id = u.id
                        OR EXISTS (
                            SELECT 1 FROM team_memberships tm
                            WHERE tm.team_id = tr.team_id AND tm.user_id = u.id
                        )
                    )
                    AND tr.ends_on >= ($2::timestamptz AT TIME ZONE 'Europe/Moscow')::date
                    ORDER BY tr.starts_on ASC
                    LIMIT 20
                    """,
                    user_id,
                    cutoff,
                )

            return [
                {
                    "title": r["title"],
                    "tripTitle": r["trip_title"],
                    "eventTimeUtc": ensure_utc_dt(r["event_time"]).isoformat(),
                    "description": r["description"],
                }
                for r in rows
            ]
    except asyncpg.UndefinedTableError:
        return []
    except Exception as e:
        logger.debug("PostgreSQL trips lookup error for %s: %s", user_id, redact_secrets(e))
        return []


