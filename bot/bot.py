_TIME_MIN_RE = re.compile(r"^(\d+)(?:m|м|мин|min)$")
_TIME_HR_RE = re.compile(r"^(\d+)(?:h|ч|час|часа|часов)$")
_TIME_DAY_RE = re.compile(r"^(\d+)(?:d|д|дн|дня|дней|день)$")


def parse_reminder_text(payload: str) -> tuple[str, int]:
    parts = payload.strip().split()
    if not parts:
        return "Напоминание", 15
    if len(parts) == 1:
        return parts[0][:255], 15

    last = parts[-1].lower()
    minutes: Optional[int] = None
    consumed = 1

    m_min = _TIME_MIN_RE.match(last)
    m_hr = _TIME_HR_RE.match(last)
    m_day = _TIME_DAY_RE.match(last)

    if m_min:
        minutes = min(MAX_REMINDER_MINUTES, max(1, int(m_min.group(1))))
    elif m_hr:
        minutes = min(MAX_REMINDER_MINUTES, max(1, int(m_hr.group(1))) * 60)
    elif m_day:
        minutes = min(MAX_REMINDER_MINUTES, max(1, int(m_day.group(1))) * 1440)
    elif re.match(r"^\d{1,2}:\d{2}$", last):
        hh, mm = map(int, last.split(":"))
        if 0 <= hh <= 23 and 0 <= mm <= 59:
            now = datetime.now(MSK_TZ)
            target = now.replace(hour=hh, minute=mm, second=0, microsecond=0)
            if target <= now:
                target += timedelta(days=1)
            minutes = max(1, int((target - now).total_seconds() // 60))
    elif len(parts) >= 3 and parts[-2].isdigit():
        qty = int(parts[-2])
        if last in ("m", "м", "мин", "мин.", "минут", "минуту", "минуты", "min"):
            minutes = min(MAX_REMINDER_MINUTES, max(1, qty))
            consumed = 2
        elif last in ("h", "ч", "ч.", "час", "часа", "часов"):
            minutes = min(MAX_REMINDER_MINUTES, max(1, qty) * 60)
            consumed = 2
        elif last in ("d", "д", "дн", "дней", "дня", "день"):
            minutes = min(MAX_REMINDER_MINUTES, max(1, qty) * 1440)
            consumed = 2

    if minutes is not None:
        if len(parts) > consumed + 1 and parts[-consumed - 1].lower() in ("через", "в", "на"):
            consumed += 1
        title = " ".join(parts[:-consumed]).strip()[:255]
        return (title or "Напоминание"), minutes

    return payload.strip()[:255], 15


_CUSTOM_DT_RE = re.compile(
    r"^\s*(\d{1,2}):(\d{2})(?:\s+(\d{1,2})(?:[\s./-]+(\d{1,2})(?:[\s./-]+(\d{4}))?)?)?\s*$"
)


def parse_custom_datetime(text: str) -> Optional[datetime]:
    """Parse 'HH:MM [DD [MM [YYYY]]]' (MSK) with defaults for today/current month/year."""
    m = _CUSTOM_DT_RE.match(text or "")
    if not m:
        return None
    hh = int(m.group(1))
    mm = int(m.group(2))
    now_msk = datetime.now(MSK_TZ)
    day = int(m.group(3)) if m.group(3) is not None else now_msk.day
    month = int(m.group(4)) if m.group(4) is not None else now_msk.month
    year = int(m.group(5)) if m.group(5) is not None else now_msk.year
    try:
        local_dt = datetime(year, month, day, hh, mm, tzinfo=MSK_TZ)
    except ValueError:
        return None
    utc_dt = local_dt.astimezone(timezone.utc)
    if utc_dt <= datetime.now(timezone.utc):
        return None
    return utc_dt


def parse_create_reminder_input(payload: str) -> tuple[str, datetime]:
    """Parse '<text> <HH:MM [DD [MM [YYYY]]]>' or '<text> <15m|2h|1d>' into (title, remind_at_utc)."""
    cleaned = (payload or "").strip()
    m = re.search(
        r"(\d{1,2}:\d{2}(?:\s+\d{1,2}(?:[\s./-]+\d{1,2}(?:[\s./-]+\d{4})?)?)?)\s*$",
        cleaned,
    )
    if m:
        custom_dt = parse_custom_datetime(m.group(1))
        if custom_dt is not None:
            title_part = cleaned[: m.start()].strip()
            title_part = re.sub(r"\s+(?:в|на)\s*$", "", title_part, flags=re.IGNORECASE).strip()
            return (title_part[:255] or "Напоминание"), custom_dt
    title, minutes = parse_reminder_text(cleaned)
    return title, datetime.now(timezone.utc) + timedelta(minutes=minutes)


def format_dt(dt: datetime) -> str:
    return dt.strftime("%d.%m.%Y %H:%M")


async def deliver_notification_to_chats(
    notif_id: Optional[int],
    user_id: str,
    notif_type: str,
    title: str,
    message: str,
    target_chat_ids: Optional[list[int]] = None,
) -> int:
    chat_ids = target_chat_ids if target_chat_ids is not None else await get_chats_by_user(user_id)
    if not chat_ids:
        return 0

    icon = NOTIFICATION_ICONS.get(notif_type, "🔔")
    now_dt = datetime.now(timezone.utc)
    delivered_count = 0

    async def deliver_one(chat_id: int) -> None:
        nonlocal delivered_count
        try:
            claimed = await try_claim_notification_delivery(chat_id, now_dt, notif_id)
            if not claimed:
                return

            msg_text = format_notification_message(icon, title, message)
            ok, permanent = await send_telegram_with_retry(
                chat_id, msg_text, notification_action_keyboard(notif_id or 0)
            )
            if ok:
                delivered_count += 1
            elif not permanent:
                await unclaim_notification_delivery(chat_id, notif_id)
        except Exception as e:
            logger.error("Unexpected error delivering notification %s to chat %s: %s", notif_id, chat_id, redact_secrets(e))

    await asyncio.gather(*(deliver_one(cid) for cid in chat_ids))
    return delivered_count


